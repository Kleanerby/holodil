export type Area = {
  slug: string;
  kind: "district" | "suburb";
  name: string;
  /** «в Советском районе», «в Боровлянах» */
  where: string;
  h1: string;
  title: string;
  description: string;
  queries: string[];
  /** положение на схеме Минска, проценты */
  x: number;
  y: number;
  arrival: string;
  /** доплата за выезд, BYN (0 — в черте города) */
  fee: number;
  places: string[];
  streets: string[];
  metro?: string[];
  /** чем район отличается с точки зрения ремонта */
  profile: string;
  typical: { t: string; d: string }[];
  tip: string;
};

const d = (
  a: Omit<Area, "kind" | "h1" | "title" | "description" | "queries" | "fee"> & { desc: string; extra?: string[] },
): Area => ({
  ...a,
  kind: "district",
  fee: 0,
  h1: `Ремонт холодильников ${a.where}`,
  title: `Ремонт холодильников ${a.where} Минска — мастер на дом за ${a.arrival}`,
  description: a.desc,
  queries: [...new Set([
    `ремонт холодильников ${a.name.toLowerCase()} район`,
    `ремонт холодильников ${a.where.replace("районе", "районе минска")}`,
    ...a.places.slice(0, 3).map((p) => `ремонт холодильников ${p.toLowerCase()}`),
    ...(a.extra ?? []),
  ])],
});

