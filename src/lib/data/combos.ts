export type Combo = ComboSeed & {
  b: Brand;
  f: Fault;
  title: string;
  description: string;
  causes: Cause[];
  from: number;
};

/** Причины неисправности, пересчитанные под марку: узлы из её слабых мест поднимаются выше */
function reweight(seed: ComboSeed, b: Brand, f: Fault): Cause[] {
  const weak = new Map(b.weak.map((w) => [w.part, w]));
  const list = f.causes.filter((c) => !seed.skip?.includes(c.part)).map((c) => {
    const w = weak.get(c.part);
    let k = w ? 1.6 : 0.7;
    if (c.part === seed.top) k = 2.6;
    return { ...c, share: c.share * k, why: w ? `${w.d} ${c.why}` : c.why, from: w ? Math.max(c.from, w.from) : c.from, service: c.service ?? w?.service };
  });
  // главный узел может отсутствовать в общем списке причин — добавляем из слабых мест марки
  if (!list.some((c) => c.part === seed.top)) {
    const w = weak.get(seed.top);
    if (w) list.push({ part: w.part, name: w.t, share: 60, why: w.d, fix: "Диагностика и замена узла", from: w.from, service: w.service });
  }
  const sum = list.reduce((n, c) => n + c.share, 0);
  return list
    .map((c) => ({ ...c, share: Math.max(3, Math.round((c.share / sum) * 100)) }))
    .sort((a, c) => (c.part === seed.top ? 1 : 0) - (a.part === seed.top ? 1 : 0) || c.share - a.share)
    .slice(0, 4);
}

export const combos: Combo[] = comboSeeds.map((s) => {
  const b = brandBySlug(s.brand)!;
  const f = faultBySlug(s.fault)!;
  const causes = reweight(s, b, f);
  const from = Math.min(...causes.map((c) => c.from));
  return {
    ...s,
    b,
    f,
    causes,
    from,
    title: `${s.h1} — причины и ремонт в Минске от ${from} BYN`,
    description: `${s.h1}: ${s.insight.split(". ")[0]}. Диагностика на дому в Минске, выезд за 1–2 часа, ремонт от ${from} BYN.`,
  };
});

export const comboBy = (brand: string, fault: string) => combos.find((c) => c.brand === brand && c.fault === fault);
export const combosOfBrand = (brand: string) => combos.filter((c) => c.brand === brand);
export const combosOfFault = (fault: string) => combos.filter((c) => c.fault === fault);
